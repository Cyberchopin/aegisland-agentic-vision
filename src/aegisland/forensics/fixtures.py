"""Deterministic minimal ULog serializer ONLY for synthetic parser tests."""

from __future__ import annotations

import json
import struct
from pathlib import Path

from .model import JETSON_CLOCK, sha256


def _message(kind: str, payload: bytes) -> bytes:
    return struct.pack("<HB", len(payload), ord(kind)) + payload


def synthetic_ulog(
    *, rollback: bool = True, nonfinite: bool = False, missing_field: bool = False
) -> bytes:
    data = bytearray(b"ULog\x01\x12\x35\x01" + struct.pack("<Q", 1_000_000))
    marker = b"synthetic-only-v1"
    key = f"char[{len(marker)}] forensics_fixture".encode()
    data += _message("I", bytes([len(key)]) + key + marker)
    formats = [
        (
            b"vehicle_local_position:uint64_t timestamp;bool xy_valid;bool z_valid;"
            b"bool v_xy_valid;bool v_z_valid;"
        ),
        b"vehicle_status:uint64_t timestamp;uint8_t nav_state;bool failsafe;",
        b"actuator_motors:uint64_t timestamp;float[2] control;",
    ]
    if missing_field:
        formats[0] = b"vehicle_local_position:uint64_t timestamp;bool xy_valid;"
    for definition in formats:
        data += _message("F", definition)
    for identifier, topic in enumerate(
        ("vehicle_local_position", "vehicle_status", "actuator_motors")
    ):
        data += _message("A", struct.pack("<BH", 0, identifier) + topic.encode())
    for index, timestamp in enumerate((1_000_000, 2_000_000, 1_500_000 if rollback else 3_000_000)):
        position = (index != 1,) if missing_field else (index != 1, True, index != 1, True)
        data += _message("D", struct.pack("<HQ" + "?" * len(position), 0, timestamp, *position))
        data += _message(
            "D", struct.pack("<HQB?", 1, timestamp, 3 if index == 0 else 4, index == 1)
        )
        control = float("nan") if nonfinite and index == 1 else (0.99 if index == 1 else 0.4)
        data += _message("D", struct.pack("<HQff", 2, timestamp, control, 0.3))
    return bytes(data)


def jetson_row(index: int = 0) -> dict:
    return {
        "schema_version": 1,
        "clock": JETSON_CLOCK,
        "timestamp": 9_000_000_000 + index * 10**9,
        "frame_id": index,
        "depth_coverage": 0.95,
        "invalid_depth_ratio": 0.05,
        "line_confidence": 0.9,
        "obstacle_distance_m": 3.0,
        "mode": "line_follow",
        "decision": "recorded_observation_only",
        "latency_ms": 12.0,
        "dropped_frame": False,
        "source_hashes": {"synthetic_source": sha256(b"no real camera")},
        "executed": False,
    }


def _jsonl(rows: list[dict]) -> bytes:
    return (
        "\n".join(json.dumps(row, sort_keys=True, allow_nan=False) for row in rows) + "\n"
    ).encode()


def fixture_payloads() -> dict[str, bytes]:
    bad_rows = [jetson_row(i) for i in range(3)]
    bad_rows[1].update(
        depth_coverage=0.2,
        invalid_depth_ratio=0.8,
        line_confidence=0.1,
        latency_ms=180.0,
        dropped_frame=True,
        mode="review",
        frame_id=3,
    )
    bad_rows[2].update(timestamp=9_500_000_000, tracking_valid=False, frame_id=2)
    ulog, jetson = synthetic_ulog(rollback=False), _jsonl([jetson_row(i) for i in range(3)])
    evidence = _jsonl(
        [
            {
                "event_id": "synthetic-pair-1",
                "px4_boot_us": 1_000_000,
                "jetson_monotonic_ns": 9_000_000_000,
                "uncertainty_us": 100,
            },
            {
                "event_id": "synthetic-pair-2",
                "px4_boot_us": 3_000_000,
                "jetson_monotonic_ns": 11_000_000_000,
                "uncertainty_us": 100,
            },
        ]
    )
    alignment = {
        "schema_version": 1,
        "executed": False,
        "method": "paired-clock-observation",
        "source_hashes": {"px4": sha256(ulog), "jetson": sha256(jetson)},
        "evidence_file": "sync-evidence.jsonl",
        "evidence_sha256": sha256(evidence),
    }
    return {
        "synthetic.ulg": synthetic_ulog(),
        "jetson.jsonl": _jsonl(bad_rows),
        "aligned.ulg": ulog,
        "aligned-jetson.jsonl": jetson,
        "sync-evidence.jsonl": evidence,
        "alignment.json": (json.dumps(alignment, indent=2, sort_keys=True) + "\n").encode(),
        "corrupt.ulg": b"not a PX4 ULog\x00",
        "truncated.ulg": synthetic_ulog()[:-2],
        "nonfinite.ulg": synthetic_ulog(nonfinite=True),
        "missing-fields.ulg": synthetic_ulog(missing_field=True),
        "invalid-jetson.jsonl": b'{"timestamp":1}\n{"broken":\n{"latency_ms":NaN}\n',
        "empty.jsonl": b"",
        "empty.ulg": b"",
        "README.md": (
            b"# Synthetic fixtures only\n\n"
            b"Generated by `python -m aegisland.forensics fixtures --output PATH`.\n"
            b"No aircraft, camera, actual PX4 runtime, map or competition data was used.\n"
            b"These minimal self-describing binary ULogs test decoding and rules only.\n"
            b"`synthetic.ulg` and `jetson.jsonl` contain rollback and anomaly scenarios.\n"
            b"`aligned*` plus `alignment.json` exercise conditional bounded interpolation.\n"
            b"Clock evidence is invented and proves no physical synchronization.\n"
            b"`nonfinite`, `missing-fields`, `corrupt`, `truncated`, `invalid`, and `empty`\n"
            b"exercise validation and partial/unknown results. All outputs executed=False.\n"
        ),
    }


def write_fixtures(output: Path) -> None:
    payloads = fixture_payloads()
    for name, data in payloads.items():
        target = output / name
        if target.exists() and target.read_bytes() != data:
            raise ValueError(f"Refusing to overwrite a different fixture/input: {target}")
    output.mkdir(parents=True, exist_ok=True)
    for name, data in payloads.items():
        target = output / name
        if not target.exists():
            with target.open("xb") as handle:
                handle.write(data)
